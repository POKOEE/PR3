import math

r = float(input("Введите радиус шара r: "))
p = float(input("Введите первую диагональ ромба p: "))
d = float(input("Введите вторую диагональ ромба d: "))

if r > 0 and p > 0 and d > 0:
    # Высота ромба
    h = (p * d) / math.sqrt(p ** 2 + d ** 2)

    if 2 * r <= h:
        print(f"Шар радиусом {r} ПРОЙДЁТ через отверстие (высота ромба = {h:.4f})")
    else:
        print(f"Шар радиусом {r} НЕ ПРОЙДЁТ через отверстие (высота ромба = {h:.4f})")
else:
    print("Ошибка: все значения должны быть положительными!")