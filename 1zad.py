m = int(input("Введите количество минут: "))
s = int(input("Введите количество секунд: "))

if m >= 0 and 0 <= s < 60:
    total = m * 60 + s
    print(f"Общее время в секундах: {total}")
else:
    print("Ошибка: неверные данные.")
    print("Минуты и секунды должны быть неотрицательными, секунды — от 0 до 59.")